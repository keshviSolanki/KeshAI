import PDFDocument from "pdfkit";
import fs from "fs";
import path from "path";

import { getModel } from "../utils/model.js";
import { checkAgentLimit } from "../config/agentRateLimit.js";
import { deductCredits } from "../utils/deductCredits.js";

export const pdfAgent = async (state) => {
  try {
    await checkAgentLimit(state.userId, "pdf");
    await deductCredits(state.userId, "pdf");

    const llm = getModel("pdf");

    const aiResponse = await llm.invoke(`
Create a professional document about:

${state.prompt}

Rules:
- Generate a professional title.
- Generate an introduction.
- Generate multiple sections.
- Generate bullet points where required.
- Generate a conclusion.
- No markdown formatting.
- No code blocks.
- No ** symbols.
- No ### headings.
- Return plain text only.
`);

    const rawContent =
      typeof aiResponse?.content === "string"
        ? aiResponse.content.trim()
        : state.prompt;

    const lines = rawContent.split("\n").filter((line) => line.trim());

    const generatedTitle =
      lines[0] && lines[0].length < 120
        ? lines[0].replace(/^[#*\s]+|[#*\s]+$/g, "")
        : state.prompt;

    const cleanContent = rawContent
      .replace(/\*\*/g, "")
      .replace(/```/g, "")
      .replace(/^#{1,6}\s*/gm, "")
      .trim();

    const fileName = `pdf-${Date.now()}.pdf`;

    // Save PDFs locally
    const outputDirectory = path.resolve(process.cwd(), "generated-files");

    await fs.promises.mkdir(outputDirectory, {
      recursive: true,
    });

    const filePath = path.join(outputDirectory, fileName);

    const doc = new PDFDocument({
      size: "A4",
      margin: 50,
      bufferPages: true,
      info: {
        Title: generatedTitle,
        Author: "kesh.AI",
        Subject: state.prompt,
        Creator: "kesh.AI PDF Agent",
      },
    });

    const chunks = [];

    doc.on("data", (chunk) => {
      chunks.push(chunk);
    });

    const pdfFinished = new Promise((resolve, reject) => {
      doc.on("end", resolve);
      doc.on("error", reject);
    });

    // PDF title
    doc.fontSize(26).fillColor("#111827").text(generatedTitle, {
      align: "center",
    });

    doc.moveDown();

    doc
      .fontSize(10)
      .fillColor("#6B7280")
      .text(`Generated on ${new Date().toLocaleString()}`, {
        align: "center",
      });

    doc.moveDown(3);

    // PDF content
    doc.fontSize(12).fillColor("#374151").text(cleanContent, {
      align: "left",
      lineGap: 6,
    });

    doc.moveDown(2);

    doc.fontSize(10).fillColor("#9CA3AF").text("Generated by kesh.AI", {
      align: "center",
    });

    doc.end();

    await pdfFinished;

    const pdfBuffer = Buffer.concat(chunks);

    await fs.promises.writeFile(filePath, pdfBuffer);

    const downloadUrl = `http://localhost:${process.env.PORT || 8003}/generated-files/${fileName}`;

    return {
      ...state,
      response: `
# ✅ PDF Generated Successfully

📄 **${generatedTitle}**

📥 [Download PDF](${downloadUrl})
      `.trim(),
    };
  } catch (error) {
    console.error("PDF Agent Error:", error);

    return {
      ...state,
      response: "❌ Failed to generate PDF.",
    };
  }
};
